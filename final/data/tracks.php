function track(string $title, string $playlist, string $href): array
{
    return [
        'title' => $title,
        'meta' => 'Song • ' . $playlist,
        'href' => $href,
    ];
}

function randomTracks(array $tracks, int $count = 5): array
{
    shuffle($tracks);
    return array_slice($tracks, 0, min($count, count($tracks)));
}

